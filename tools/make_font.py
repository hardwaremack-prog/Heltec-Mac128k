out = ["// 5x7 OLED font (generated by tools/make_font.py). Columns, LSB = top row. Codes 32..95.",
       "#pragma once", "static const uint8_t OLED_FONT[64][5] = {"]
for c in range(32, 96):
    g = G.get(chr(c), G['?'])
    cols = []
    for x in range(5):
        v = 0
        for y in range(7):
            if g[y][x] == '#': v |= 1 << y
        cols.append("0x%02X" % v)
    out.append("  {%s},  // %r" % (", ".join(cols), chr(c)))
out.append("};")
open("Heltec-Mac/oledfont.h", "w").write("\n".join(out) + "\n")
