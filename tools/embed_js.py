# Generates MacMesh/macfiles_js.h (served by the board as /macfiles.js) from web/macfiles.js.
#   python3 tools/embed_js.py
import os
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, '..', 'web', 'macfiles.js'), encoding='utf-8').read()
assert ')JS"' not in src
out = '// Generated by tools/embed_js.py from web/macfiles.js - edit that file, not this one.\n#pragma once\n' \
      'static const char MACFILES_JS[] PROGMEM = R"JS(' + src + ')JS";\n'
open(os.path.join(here, '..', 'MacMesh', 'macfiles_js.h'), 'w', encoding='utf-8').write(out)
print('macfiles_js.h', len(src), 'bytes of JS')
