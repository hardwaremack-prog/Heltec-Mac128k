# Generates Heltec-Mac/macfiles_js.h (served by the board as /macfiles.js and /sit-arsenic.js)
# from web/macfiles.js, web/sit-arsenic.js and web/imagewriter.js (also served as /imagewriter.js).    python3 tools/embed_js.py
import os
here = os.path.dirname(os.path.abspath(__file__))
def js(name):
    s = open(os.path.join(here, '..', 'web', name), encoding='utf-8').read()
    assert ')JS"' not in s
    return s
import hashlib
ver = hashlib.md5((js('macfiles.js') + js('sit-arsenic.js') + js('imagewriter.js')).encode()).hexdigest()[:8]
out = ('// Generated by tools/embed_js.py from web/macfiles.js and web/sit-arsenic.js - edit those, not this.\n'
       '#pragma once\n'
       '// The page asks for the scripts with ?v=<version>, so browsers never use a stale copy\n'
       '#define MACFILES_JS_URL "/macfiles.js?v=' + ver + '"\n'
       '#define SIT_ARSENIC_JS_URL "/sit-arsenic.js?v=' + ver + '"\n'
       '#define IMAGEWRITER_JS_URL "/imagewriter.js?v=' + ver + '"\n'
       'static const char MACFILES_JS[] PROGMEM = R"JS(' + js('macfiles.js') + ')JS";\n'
       '// LGPL 2.1 (port of XADMaster code), see web/sit-arsenic.js\n'
       'static const char SIT_ARSENIC_JS[] PROGMEM = R"JS(' + js('sit-arsenic.js') + ')JS";\n'
       '// the virtual ImageWriter: printer-port bytes -> pages -> PDF\n'
       'static const char IMAGEWRITER_JS[] PROGMEM = R"JS(' + js('imagewriter.js') + ')JS";\n')
open(os.path.join(here, '..', 'Heltec-Mac', 'macfiles_js.h'), 'w', encoding='utf-8').write(out)
print('macfiles_js.h written')
